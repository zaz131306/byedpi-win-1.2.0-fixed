#!/bin/sh
# fix.sh — то же, что fix.bat, для Linux / macOS / WSL / Git Bash.
# Шаг 1: что реально работает и чем заблокирован каждый сайт.
# Шаг 2: подбор стратегии отдельно под каждый сайт + склейка в группы --hosts.
# Шаг 3: перепроверка на склеенной строке.
#
# Вывод каждого шага идёт И в окно, И в fix-log.txt: этим занимается
# host/runlog.py (в Windows нет `tee`, а через конвейер теряется код возврата).
cd "$(dirname "$0")" || exit 2

PY=python3
command -v $PY >/dev/null 2>&1 || PY=python
HERE=$(pwd)
LOG="$HERE/fix-log.txt"

{
    echo "===== fix.sh запущен $(date '+%Y-%m-%d %H:%M:%S') ====="
    echo "каталог: $HERE"
    echo "python:  $PY"
} > "$LOG"

# --- какие сайты подбирать ---------------------------------------------------
# Если рядом лежит dnsfix-pins.json (его пишет DNSFIX), список берётся оттуда:
# именно те домены, где нашлась подмена, и БЕЗ тех, у кого соединение не
# поднимается вовсе, — там блокировка по адресу, и аргументы ciadpi не помогут.
URLS=""
if [ -f "$HERE/dnsfix-pins.json" ]; then
    echo "===== список сайтов из dnsfix-pins.json =====" >> "$LOG"
    URLS=$("$PY" "$HERE/DNSFIX.py" --emit-fix-urls 2>>"$LOG")
    echo "emit-fix-urls код возврата: $?" >> "$LOG"
fi
if [ -z "$URLS" ]; then
    URLS="--url https://rutor.info/ --url https://rutracker.org/forum/index.php --url https://www.youtube.com/ --url http://rutor.info/"
    echo "dnsfix-pins.json нет — беру список по умолчанию" >> "$LOG"
fi
echo "URLS: $URLS" >> "$LOG"
echo
echo " Сайты для подбора:"
for u in $URLS; do
    case "$u" in
        --url) ;;
        *) echo "   $u" ;;
    esac
done

RUNLOG="$HERE/host/runlog.py"

echo
echo "========================================================================"
echo " ШАГ 1 из 3. Что реально работает и чем заблокирован каждый сайт"
echo "========================================================================"
# shellcheck disable=SC2086
"$PY" "$RUNLOG" --log "$LOG" --append -- "$PY" "$HERE/host/verify.py" $URLS \
    --both-schemes --json "$HERE/verify-result.json"
RC1=$?
echo " [1/3] код возврата $RC1"
if [ "$RC1" = "0" ]; then
    echo
    echo "========================================================================"
    echo " Обход УЖЕ работал — доказано на заблокированном сайте."
    echo " Менять ничего не надо. Если что-то не открывается — запусти DIAG.sh."
    echo "========================================================================"
    exit 0
fi

echo
echo "========================================================================"
echo " ШАГ 2 из 3. Подбор стратегии ОТДЕЛЬНО под каждый сайт"
echo "             (прокси перезапускается, браузер в это время НЕ РАБОТАЕТ;"
echo "              занимает от 3 до 20 минут)"
echo "========================================================================"
# --fail-fast намеренно НЕ указан: с ним подбор останавливается на первом же
# непробитом сайте, а склеиваются и применяются всё равно только победители.
# shellcheck disable=SC2086
"$PY" "$RUNLOG" --log "$LOG" --append -- "$PY" "$HERE/host/pick_multi.py" $URLS --apply -y
RC2=$?
echo " [2/3] код возврата $RC2"

echo
echo "========================================================================"
echo " ШАГ 3 из 3. Перепроверка на склеенной строке"
echo "========================================================================"
# shellcheck disable=SC2086
"$PY" "$RUNLOG" --log "$LOG" --append -- "$PY" "$HERE/host/verify.py" $URLS \
    --both-schemes --json "$HERE/verify-result.json"
RC3=$?
echo " [3/3] код возврата $RC3"

if [ "$RC3" = "0" ]; then
    echo
    echo " ГОТОВО. Обход доказан: заблокированные сайты открываются через прокси."
    echo " Настройки сохранены в config.json (strategy=custom)."
    exit 0
fi

cat <<'TEXT'

------------------------------------------------------------------------
Открылось не всё. Три причины, и лечатся они по-разному:

 1. Сайт заблокирован ПО IP, а не по содержимому пакета. Чаще всего это
    Instagram, Facebook, Threads. Рабочих аргументов ciadpi для них НЕ
    СУЩЕСТВУЕТ в принципе — нужен туннель: SYNTH.sh (многоканальная схема)
    или VPN.md (AmneziaWG на своём VPS). verify.py помечает такие сайты
    строкой «ПОХОЖЕ НА БЛОКИРОВКУ ПО IP».

 2. Провайдер блокирует по TLS-отпечатку клиента. Это лечится не
    аргументами ciadpi, а транспортом: туннель.

 3. HTTP/3 (QUIC) уводит трафик мимо прокси. about:config:
    network.http.http3.enable = false, network.dns.http3_echconfig.enabled = false,
    затем ПОЛНОСТЬЮ перезапустите браузер.

Подробности: FIX.md, разделы 4 и 9. Весь результат — в verify-result.json,
весь вывод — в fix-log.txt (его и присылай, если что-то не так).
------------------------------------------------------------------------
TEXT
exit 1
